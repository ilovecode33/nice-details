/** Replaces `{name}` placeholders, leaving unknown placeholders untouched. */
export function interpolate(
  template: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match,
  );
}

/** Locale-aware translator with simple interpolation. */
export function useOkrI18n() {
  const { locale, setLocale, t } = useLocale();
  const current = (
    LOCALES.includes(locale as Locale) ? locale : DEFAULT_LOCALE
  ) as Locale;

  return {
    locale: current,
    setLocale,
    intlLocale: INTL_LOCALES[current],
    t: (key: string, params?: Record<string, string | number>) =>
      interpolate(t(key), params),
  };
}
